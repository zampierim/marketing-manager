let currentCategory = 'Reforma Tributária';
let ideas = [];
let idCounter = 1;

const lines = rawText.split('\n');
for (let line of lines) {
    line = line.trim();
    if (!line) continue;
    
    if (line.startsWith('===')) {
        currentCategory = line.replace(/===/g, '');
        continue;
    }
    
    let title = line.replace(/^\d+\.\s*/, '').replace(/^[*\-]\s*/, '').trim();
    if (title) {
        ideas.push({
            id: 'pilar-' + currentCategory.substring(0,3).toLowerCase() + '-' + idCounter++,
            title: title,
            usageCount: 0,
            series: currentCategory,
            audience: 'Externo'
        });
    }
}

// Write the parsed JSON directly into app.js
let appJs = fs.readFileSync('app.js', 'utf-8');

// The new window.ideasData array
let newIdeasStr = 'window.ideasData = ' + JSON.stringify(ideas, null, 2) + ';';

// Use regex to replace the old array. We need to find `window.ideasData = [...];`
// Since the old array ends with `];` or `]\n;`, let's find the assignment and the first `];` that aligns.
// Better yet, since we know it's a huge block, we can replace everything between `window.ideasData = [` and `];`
const startIdx = appJs.indexOf('window.ideasData = [');
if (startIdx !== -1) {
    const endIdx = appJs.indexOf('];', startIdx);
    if (endIdx !== -1) {
        appJs = appJs.substring(0, startIdx) + newIdeasStr + appJs.substring(endIdx + 2);
        fs.writeFileSync('app.js', appJs, 'utf-8');
        console.log('Successfully replaced ideasData in app.js. Total ideas:', ideas.length);
    } else {
        console.log('Could not find ]; for ideasData.');
    }
} else {
    console.log('Could not find window.ideasData = [ in app.js.');
}

